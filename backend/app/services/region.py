def normalize_region(raw: str) -> str:
    """수집된 region 문자열을 정규화된 짧은 이름으로 변환.

    매핑 테이블에서 정확히 일치하면 변환, 아니면 원본 유지.
    """
    if not raw:
        return raw
    stripped = raw.strip()
    return _REGION_ALIASES.get(stripped, stripped)
